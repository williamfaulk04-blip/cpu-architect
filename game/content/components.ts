function createComponent(content: ComponentContent): GpuComponent {
  const socketId = `${content.stageId}-socket-${String(content.socketOrder + 1).padStart(2, '0')}`;

  return {
    ...content,
    stageId: content.stageId,
    stageOrder: content.stageOrder,
    socketId,
    socketOrder: content.socketOrder,
    incorrectHint: content.clue,
    achievementText: `Installed ${content.name} in the ${content.stageId.replaceAll('-', ' ')}.`,
    choices: STAGE_COMPONENT_IDS[content.stageId as keyof typeof STAGE_COMPONENT_IDS],
    assetKey: `gpu-component-${content.id}`,
    socketAssetKey: `gpu-socket-${socketId}`,
    position: {
      desktop: {
        x: 12 + (content.socketOrder % 4) * 25,
        y: 30 + Math.floor(content.socketOrder / 4) * 25,
      },
      mobile: {
        x: 10 + (content.socketOrder % 2) * 45,
        y: 25 + Math.floor(content.socketOrder / 2) * 25,
      },
    },
    enabled: content.availability === 'MVP',
  };
}

export const GPU_COMPONENTS = Object.fromEntries(
  COMPONENT_CONTENT.map((content) => [content.id, createComponent(content)]),
) as Record<GpuComponentId, GpuComponent>;

export function componentById(id: GpuComponentId) {
  return GPU_COMPONENTS[id];
}
